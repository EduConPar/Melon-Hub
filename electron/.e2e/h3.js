const { app, BrowserWindow } = require('electron');
const fs = require('fs');
require('/app/.e2e/server.js');
require('/app/main.js');
const settings = require('/app/settings.js');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let ok = true; const t = (l, c) => { if (!c) ok = false; console.log((c ? 'OK   ' : 'FAIL ') + l); };
const orders = [];
app.on('browser-window-created', (_e, w) => w.webContents.on('console-message', (e) => { if (String(e.message).startsWith('ORDEN')) orders.push(String(e.message).slice(6)); }));
const wins = () => BrowserWindow.getAllWindows();
const main = () => wins().find((w) => w.webContents.getURL().endsWith('index.html'));
const mini = () => wins().find((w) => w.webContents.getURL().includes('mini-player'));
const js = (w, code) => w.webContents.executeJavaScript(code);
const shot = async (name) => { await new Promise((r) => setTimeout(r, 300)); require('child_process').execSync(`import -window ${mini().getNativeWindowHandle().readUInt32LE(0)} /app/.e2e/${name}.png`); };
const click = (id) => js(mini(), `document.getElementById('${id}').click()`);
app.whenReady().then(async () => {
  settings.set('floatingPlayer', true); settings.set('miniPosition', null);
  await wait(4000);
  main().close(); await wait(2500);
  const [w, h] = mini().getContentSize();
  t(`Sale el flotante vertical (${w}×${h})`, mini().isVisible() && w > 290 && h > 400);
  const d = await js(mini(), `({ win: document.getElementById('mp-window-title').textContent, song: document.getElementById('mp-song').textContent,
      artist: document.getElementById('mp-artist').textContent, play: document.querySelectorAll('#mp-play rect').length === 2 ? 'pausa' : 'play',
      max: document.querySelectorAll('.title-bar-controls button')[1].getAttribute('aria-label'),
      cover: document.getElementById('mp-cover').src.split('/').pop(), fill: document.getElementById('mp-progress').style.getPropertyValue('--p') })`);
  t(`Datos: «${d.song}» · ${d.artist} · ${d.win} · ${d.play} · progreso ${d.fill}`, d.song === 'Kill Or Be Killed' && d.artist === 'Muse' && d.play === 'pausa' && parseFloat(d.fill) > 9);
  t('Botón de la barra de título = Maximizar', d.max === 'Maximize');
  await shot('win98-reproductor');
  for (const id of ['mp-prev', 'mp-next', 'mp-shuffle', 'mp-play']) await click(id);
  await js(mini(), `(() => { const p = document.getElementById('mp-progress'); p.value = 50; p.dispatchEvent(new Event('change')); })()`);
  await wait(800);
  t('Botones → ' + orders.join(', '), orders.join() === 'previoustrack,nexttrack,shuffle,toggle,seekto 150');
  const sh = await js(mini(), `document.getElementById('mp-shuffle').classList.contains('btn-active')`);
  t('Aleatorio activado se ve pulsado', sh);
  await click('mp-play'); orders.length = 0;
  await click('mp-lyrics-btn'); await wait(1500);
  const ly = await js(mini(), `({ lines: document.querySelectorAll('.mp-lyric').length, active: (document.querySelector('.mp-lyric.active') || {}).textContent })`);
  t(`Letra sincronizada: ${ly.lines} líneas, resaltada «${ly.active}»`, ly.lines === 4 && !!ly.active);
  await shot('win98-letra');
  await click('mp-lyrics-back');
  await click('mp-lists-btn'); await wait(1200);
  const pls = await js(mini(), `Array.from(document.querySelectorAll('#mp-lists-box .mp-row')).map(r => r.textContent.trim() + (r.classList.contains('current') ? ' [actual]' : ''))`);
  t('Playlists: ' + pls.join(' | '), pls.length === 2 && pls[0].includes('[actual]'));
  await shot('win98-playlists');
  await js(mini(), `document.querySelectorAll('#mp-lists-box .mp-row')[1].querySelector('button').click()`); await wait(400);
  t('"+" añade la canción a esa playlist → ' + orders.at(-1), orders.at(-1) === 'add-to-playlist 9');
  await wait(1500);
  await js(mini(), `document.querySelectorAll('#mp-lists-box .mp-row')[0].click()`); await wait(300);
  const songs = await js(mini(), `Array.from(document.querySelectorAll('#mp-lists-box .mp-row')).map(r => r.textContent.trim())`);
  t('Canciones de la playlist: ' + songs.join(' | '), songs.length === 3);
  await shot('win98-canciones');
  await js(mini(), `document.querySelectorAll('#mp-lists-box .mp-row')[1].click()`); await wait(400);
  const v = await js(mini(), `document.getElementById('mp-player').classList.contains('active')`);
  t('Elegir canción → ' + orders.at(-1) + ' y vuelve al reproductor', orders.at(-1) === 'play-playlist {"playlistId":7,"index":1}' && v);
  mini().webContents.sendInputEvent({ type: 'mouseDown', x: 150, y: 150, button: 'right', clickCount: 1 });
  mini().webContents.sendInputEvent({ type: 'mouseUp', x: 150, y: 150, button: 'right', clickCount: 1 });
  await wait(500);
  const items = await js(mini(), `Array.from(document.querySelectorAll('.mp-menu-item')).map(i => i.textContent.trim())`);
  t('Clic derecho: ' + items.join(' · '), items.join() === '➕ Añadir,Corregir…,🎵 Añadir a mi perfil,🎧 Escuchar juntos…');
  await shot('win98-menu');
  await js(mini(), `Array.from(document.querySelectorAll('.mp-menu-item')).find(i => i.textContent.includes('Corregir')).click()`); await wait(800);
  t('"Corregir…" → abre Melon Hub y manda ' + orders.at(-1), orders.at(-1) === 'fix' && main().isVisible() && !mini().isVisible());
  /* Melon Kawaii: la ventana principal cambia de interfaz y el flotante la copia al volver a salir. */
  await js(main(), `(() => { const l = document.createElement('link'); l.rel = 'stylesheet'; l.href = 'assets/interfaces/kawaii/style.css'; document.head.appendChild(l); document.getElementById('theme').remove(); st.playing = true; })()`);
  await wait(2500);
  main().close(); await wait(3500);
  const k = await js(mini(), `Array.from(document.querySelectorAll('link[data-look]')).map(l => l.href.split('/').slice(-2).join('/'))`);
  t('Kawaii copiado: ' + k.join(', '), k.some((h) => h.includes('kawaii/style.css')));
  await shot('kawaii-reproductor');
  await click('mp-lists-btn'); await wait(1200); await shot('kawaii-playlists');
  await click('mp-lists-back'); await click('mp-lyrics-btn'); await wait(1500); await shot('kawaii-letra');
  console.log(ok ? '\nTodo OK' : '\nHAY FALLOS');
  app.exit(0);
});
