const { app, BrowserWindow } = require('electron');
const fs = require('fs');
require('/app/.e2e/server.js');
require('/app/main.js');
const settings = require('/app/settings.js');
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let ok = true; const t = (l, c) => { if (!c) ok = false; console.log((c ? 'OK   ' : 'FAIL ') + l); };
const orders = [];
app.on('browser-window-created', (_e, w) => w.webContents.on('console-message', (e) => { if (String(e.message).startsWith('ORDEN')) orders.push(String(e.message).slice(6)); }));
const wins = () => BrowserWindow.getAllWindows();
const main = () => wins().find((w) => w.webContents.getURL().endsWith('index.html'));
const mini = () => wins().find((w) => w.webContents.getURL().includes('mini-player'));
const js = (w, code) => w.webContents.executeJavaScript(code);
const shot = async (name) => { await new Promise((r) => setTimeout(r, 300)); require('child_process').execSync(`import -window ${mini().getNativeWindowHandle().readUInt32LE(0)} /app/.e2e/${name}.png`); };
const info = () => js(mini(), `({ lists: document.getElementById('mp-lists-btn').textContent, vol: document.getElementById('mp-volume').value,
    volIcon: document.getElementById('mp-vol-icon').textContent, icon: document.querySelector('.title-bar-text img').src.split('/').slice(-2).join('/'),
    fs: document.documentElement.style.getPropertyValue('--fs-delta').trim(), font: getComputedStyle(document.getElementById('mp-song')).fontFamily.split(',')[0] })`);
app.whenReady().then(async () => {
  settings.set('floatingPlayer', true); settings.set('miniPosition', null);
  await wait(4000);
  main().close(); await wait(3000);
  let d = await info();
  t(`Botón de playlists: «${d.lists}»`, d.lists === '≡');
  t(`Volumen del reproductor en el flotante: ${d.vol} ${d.volIcon}`, d.vol === '40' && d.volIcon === '◄)');
  t(`Iconos del usuario (pack Oscuro): ${d.icon}`, d.icon === 'Oscuro/musicaIcon.png');
  t(`Tamaño de letra del tema: --fs-delta ${d.fs}`, d.fs !== '');
  await js(mini(), `(() => { const v = document.getElementById('mp-volume'); v.value = 0; v.dispatchEvent(new Event('input')); })()`); await wait(600);
  d = await info();
  t(`Mover el volumen a 0 → ${orders.at(-1)} · icono ${d.volIcon}`, orders.at(-1) === 'volume 0' && d.volIcon === '◄✕');
  await js(mini(), `(() => { const v = document.getElementById('mp-volume'); v.value = 80; v.dispatchEvent(new Event('input')); })()`); await wait(600);
  await shot('win98-volumen');
  for (const id of ['mp-prev', 'mp-next', 'mp-play', 'mp-play']) await js(mini(), `document.getElementById('${id}').click()`);
  await wait(500);
  t('Los demás botones siguen igual → ' + orders.slice(-4).join(', '), orders.slice(-4).join() === 'previoustrack,nexttrack,toggle,toggle');
  const btns = await js(mini(), `Array.from(document.querySelectorAll('.title-bar-controls button')).map(b => b.getAttribute('aria-label') + ' ' + Math.round(b.getBoundingClientRect().width) + 'px').join(' · ')`);
  t('Barra de título: ' + btns, /^Minimize \d+px · Maximize \d+px · Close \d+px$/.test(btns) && !/ 0px/.test(btns));
  const above = require('child_process').execSync(`xprop -id ${mini().getNativeWindowHandle().readUInt32LE(0)} _NET_WM_STATE`).toString().trim();
  t('Siempre encima (gestor de ventanas real): ' + above, /ABOVE/.test(above));
  await js(mini(), `document.getElementById('mp-min').click()`); await wait(1200);
  t('Minimizar → el flotante se minimiza', mini().isMinimized());
  t('…y sigue sonando (no manda ninguna orden)', orders.at(-1) === 'toggle');
  mini().restore(); await wait(800);
  t('Restaurar desde la barra de tareas → vuelve', !mini().isMinimized() && mini().isVisible());
  /* El usuario cambia de pack y de interfaz (Kawaii) en la ventana principal. */
  await js(mini(), `document.getElementById('mp-open').click()`); await wait(800);
  await js(main(), `(() => { localStorage.setItem('iconPack:win98', 'Claro'); const l = document.createElement('link'); l.rel = 'stylesheet';
      l.href = 'assets/interfaces/kawaii/style.css'; document.head.appendChild(l); document.getElementById('theme').remove(); st.playing = true; })()`);
  await wait(2500);
  main().close(); await wait(5000);
  d = await info();
  t(`Al volver a salir coge el pack nuevo: ${d.icon}`, d.icon === 'Claro/musicaIcon.png');
  t(`…y la interfaz Kawaii con su fuente: ${d.font}`, /Pixelify/.test(d.font));
  const [w, h] = mini().getContentSize();
  const real = await js(mini(), `(() => { const r = document.getElementById('mp').getBoundingClientRect(); return [Math.ceil(r.width), Math.ceil(r.height)]; })()`);
  t(`La ventana mide lo que la ventana Win98 dibujada (${w}×${h} = ${real.join('×')})`, w === real[0] && h === real[1]);
  await shot('kawaii-volumen');
  console.log(ok ? '\nTodo OK' : '\nHAY FALLOS');
  app.exit(0);
});
